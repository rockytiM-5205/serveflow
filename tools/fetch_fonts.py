"""Download Geist and Plus Jakarta Sans once and write frontend/shared/css/fonts.css, so ServeFlow serves its own fonts.

    python tools/fetch_fonts.py

Needs an internet connection the first time. Fonts are open source (SIL Open Font Licence). Afterwards nothing is fetched from
Google at run time: the browser loads the files from /shared/fonts/, which also works offline in the installed app.
"""
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent / "frontend" / "shared"
FAMILIES = {
    "Geist": "Geist:wght@400..700",
    "Geist Mono": "Geist+Mono:wght@400..600",
    "Plus Jakarta Sans": "Plus+Jakarta+Sans:wght@400..700",
}
# A current browser name makes Google return modern woff2 files.
UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36"


def get(url):
    with urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": UA}), timeout=30) as response:
        return response.read()


def main():
    fonts_dir = ROOT / "fonts"
    fonts_dir.mkdir(parents=True, exist_ok=True)
    blocks = ["/* Generated by tools/fetch_fonts.py. Do not edit by hand; run the script again to refresh. */"]
    for name, spec in FAMILIES.items():
        css = get(f"https://fonts.googleapis.com/css2?family={spec}&display=swap").decode()
        slug = name.lower().replace(" ", "-")
        for subset, block in re.findall(r"/\* ([\w-]+) \*/\s*(@font-face \{.*?\})", css, flags=re.S):
            if subset not in ("latin", "latin-ext"):
                continue  # Latin covers English; latin-ext adds the Naira sign and accented names
            url = re.search(r"url\((https://[^)]+\.woff2)\)", block).group(1)
            filename = f"{slug}-{subset}.woff2"
            (fonts_dir / filename).write_bytes(get(url))
            block = re.sub(r"url\(https://[^)]+\.woff2\)", f"url(../fonts/{filename})", block)
            blocks.append(f"/* {name} {subset} */\n{block}")
            print(f"  {name} ({subset}) -> shared/fonts/{filename}")
    (ROOT / "css" / "fonts.css").write_text("\n".join(blocks) + "\n", encoding="utf-8")
    print("Done. Reload the pages; fonts.css now points at the local files.")


if __name__ == "__main__":
    try:
        main()
    except OSError as exc:
        sys.exit(f"Could not download the fonts ({exc}). Check your internet connection and run this again.")
